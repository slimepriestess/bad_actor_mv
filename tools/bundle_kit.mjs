// bundle_kit.mjs: wraps the Clawd kit (kit/*.js, MIT, from claude_animation_base) in one closure → src/kit_bundle.js.
//
// Why: the kit and the hyperslop engine (src/core.js, from ignition_mv) are both written as classic scripts with
// top-level consts (W, H, clamp, pulse, ring, T, drawWorld…), and several share a name with different meanings (kit
// `ring` = spring kicks, engine `ring` = a stroked circle). Inside one closure the kit keeps its own names, p5 global
// mode still finds setup/draw on window, and the engine sees only window.CK.
//
// The kit's p5 canvas is a transparent sprite layer: the engine hands it a job (a function that paints Clawds with the
// kit API), awaits one redraw, and drawImage()s the result into its own Canvas2D frame (see clawdPass in src/core.js).
//
// Run after editing anything in kit/:  node tools/bundle_kit.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const TEMPO = JSON.parse(readFileSync('analysis/tempo.json', 'utf8'));
const read = f => readFileSync(`kit/${f}`, 'utf8');
let core = read('core.js')
  .replace('window.ready = true;', 'window.kitReady = true;')
  .replace("if (!location.search.includes('render')) devUI();", '')
  .replace("outC = document.getElementById('out'); outX = outC.getContext('2d');", '')
  .replace(/^window\.(renderAt|renderSheet|gpuInfo) = [\s\S]*?^};?$/gm, '');
// Replace the kit's paper-and-shots draw() with the sprite-layer job runner.
core = core.replace(/^function draw\(\) \{[\s\S]*?^\}$/m, `function draw() {
  if (!window.kitReady || !JOB) return;
  clear();
  push(); translate(-W / 2, -H / 2);
  BOILN = Math.floor(T * BOIL); CLAWD_N = 0; boilSeed('frame'); noiseSeed(77);
  JOB(T); CAM = null;
  flushBrush();
  pop();
}`);

const names = `W H BEAT OFF PAL clamp lerp ease easeOut backOut hash bpOf jit boilSeed seg frac beatN pulse pulse2 wob easeIn
  elasticOut kf mixCol shakeXY spring onTwos arcPt jump take stroll camBegin camEnd toScreen flash glow irisShape iris
  rectPts ellPts rrPts starPts through ribbon paint inkLine flushBrush brushWipe spinView turn clawd emote heartPts EMO
  feel emotions move dancer`.split(/\s+/).filter(Boolean);

const out = `// GENERATED by tools/bundle_kit.mjs from kit/*.js (Clawd kit, MIT: see kit/LICENSE). Do not edit; edit kit/ and rerun.
(() => {
const PROJECT = { duration: ${TEMPO.duration}, bpm: ${TEMPO.bpm}, offset: ${TEMPO.offset} };
let JOB = null;
${core}
${read('clawd.js')}
${read('timeline.js')}
window.setup = setup;
window.draw = draw;
window.CK = {
  // Paint job(t) on the transparent sprite canvas at song time t. Resolves once p5 has drawn it.
  async run(t, job) { T = t; JOB = job; await redraw(); JOB = null; return drawingContext.canvas; },
  ${names.map(n => `${n}: (typeof ${n} === 'undefined' ? undefined : ${n})`).join(',\n  ')},
  springs: ring,
};
})();
`;
writeFileSync('src/kit_bundle.js', out);
console.log('src/kit_bundle.js', out.length, 'bytes');
